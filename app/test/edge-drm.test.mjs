// Sec-MS-GEC token (edge-drm.mjs) against the Python reference (edge-tts 7.3.1).
// The expected values below are hashes computed by the reference library;
// they are deterministic outputs for fixed timestamps, not secrets.
import test from 'node:test';
import assert from 'node:assert/strict';
import { generateSecMsGec } from '../server/edge-drm.mjs';

const VECTORS = [
  [0, '52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6'],
  [1, '52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6'],
  [1234567890, 'BA405D1577B8E0CE-61F01E88539977A1A1E969572D82EECFA45FB1E5DEBD122D6ACBAF0054F959E5'],
  [1700000000, '2CD23A2CA0B2595A-F3C846C370E05F9CC83ACC5F995C5F5D87A4D0F14CE8936A0F902E64099E38A2'],
  [1763800000, '9027D1FFFB4D7F11-80B58D4C4DB198603A4FB5DE4F8309D6DB55C2FD5EEB87025DFD599F1B3D66B0'],
  [1763800199, '9027D1FFFB4D7F11-80B58D4C4DB198603A4FB5DE4F8309D6DB55C2FD5EEB87025DFD599F1B3D66B0'],
  [1763800200, 'FFD01BDEB05446A4-6040AAF9B9C28625DAD62C684EB092FCAF191AF2A07E3AF28E7FB385C88CA6FD'],
  [1763800300, 'FFD01BDEB05446A4-6040AAF9B9C28625DAD62C684EB092FCAF191AF2A07E3AF28E7FB385C88CA6FD'],
  [1999999999, '2D62557F1142BC5D-FD9C30C68FF194A5EE6B45FEFC5E2BA1D1239F88A90569AB55CFFFAA7799F40E'],
];

test('Sec-MS-GEC tokens match the edge-tts reference exactly', () => {
  for (const [t, want] of VECTORS) assert.equal(generateSecMsGec(t), want, `t=${t}`);
});

test('the token is stable inside a 5-minute bucket and changes across it', () => {
  assert.equal(generateSecMsGec(1763800000), generateSecMsGec(1763800199));
  assert.notEqual(generateSecMsGec(1763800000), generateSecMsGec(1763800200));
  assert.match(generateSecMsGec(), /^[0-9A-F]{16}-[0-9A-F]{64}$/);
});
